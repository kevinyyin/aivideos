"""dh016 narration timeline: tools/tts.py's raw takes (voice/<id>.wav + .words.json) -> tightened takes + one timeline.

Brian's raw takes run ~2.6 words/s; the explainer pace is ~3.5. So, per line: trim the edges, shorten every pause
inside the line to PAUSE s, time-stretch by TEMPO (ffmpeg atempo keeps the pitch), and remap the word timings through
the same cuts. Lines are then laid end to end from START with GAP s between them (+ EXTRA before a beat).
Writes voice/fast/<id>.wav, timeline.json (make_cues.py) and timeline.js (shots.js: LINES + WORDS for the caption).
Run: python3 -I videos/dh016-pisa-dig/make_voice.py
"""
import json
import subprocess
from pathlib import Path

import numpy as np
from scipy.io import wavfile

V = Path(__file__).resolve().parent
FF = str(V.parents[1] / "node_modules/@ffmpeg-installer/darwin-arm64/ffmpeg")
TEMPO, PAUSE, GAP, THR, MIN_SIL = 1.25, 0.09, 0.08, 0.012, 0.13
ORDER = [ln["id"] for ln in json.loads((V / "voice.json").read_text())["lines"]]
START = {"n01_hook": 0.12}   # the hook is the first sound (no title card): frame 4
EXTRA = {}   # gaps stay <= 0.15 s (playbook: back to back)


def tighten(lid):
    sr, y = wavfile.read(V / "voice" / f"{lid}.wav")
    y = y.astype(np.float32) / (32768.0 if y.dtype == np.int16 else 1.0)
    hop = sr // 100
    rms = np.sqrt(np.convolve(y ** 2, np.ones(hop) / hop, mode="same"))[::hop]
    loud = rms > THR
    idx = np.flatnonzero(loud)
    a, b = max(0, idx[0] - 2), min(len(loud), idx[-1] + 6)   # keep 20 ms before, 60 ms after
    keep = []   # [t0, t1) spans of the original kept, in seconds
    s = a
    i = a
    while i < b:
        if not loud[i]:
            j = i
            while j < b and not loud[j]:
                j += 1
            if (j - i) / 100 >= MIN_SIL and j < b:
                half = int(PAUSE * 50)
                keep.append((s / 100, (i + half) / 100))
                s = j - half
            i = j
        else:
            i += 1
    keep.append((s / 100, b / 100))
    parts = []
    fade = int(0.008 * sr)
    for t0, t1 in keep:
        p = y[int(t0 * sr):int(t1 * sr)].copy()
        p[:fade] *= np.linspace(0, 1, fade)
        p[-fade:] *= np.linspace(1, 0, fade)
        parts.append(p)
    out = np.concatenate(parts)

    def tmap(t):   # original time -> tightened time (before tempo)
        acc = 0.0
        for t0, t1 in keep:
            if t < t0:
                return acc
            if t <= t1:
                return acc + t - t0
            acc += t1 - t0
        return acc

    (V / "voice/fast").mkdir(exist_ok=True)
    tmp = V / "voice/fast" / f"{lid}.tmp.wav"
    wavfile.write(tmp, sr, (out * 32767).astype(np.int16))
    dst = V / "voice/fast" / f"{lid}.wav"
    subprocess.run([FF, "-v", "error", "-y", "-i", str(tmp), "-af", f"atempo={TEMPO}", "-ar", str(sr), "-ac", "1", str(dst)], check=True)
    tmp.unlink()
    dur = len(out) / sr / TEMPO
    words = json.loads((V / "voice" / f"{lid}.words.json").read_text())["words"]
    w2 = [[w, round(tmap(a0) / TEMPO, 3), round(min(dur, tmap(a1) / TEMPO), 3)] for w, a0, a1 in words]
    return dur, w2


def main():
    lines, words, t = {}, [], 0.0
    for lid in ORDER:
        dur, w = tighten(lid)
        t = START.get(lid, t + EXTRA.get(lid, 0.0))
        lines[lid] = [round(t, 3), round(t + dur, 3)]
        for i, (word, a, b) in enumerate(w):   # caption word holds until the next word starts (no blank flicker)
            nxt = w[i + 1][1] if i + 1 < len(w) else b + 0.25
            words.append([round(t + a, 3), round(t + nxt, 3), word])
        print(f"{lid:16} {t:6.2f} -> {t + dur:6.2f}  ({dur:.2f} s, {len(w)} words)")
        t += dur + GAP
    (V / "timeline.json").write_text(json.dumps({"lines": lines, "words": words}, indent=1))
    (V / "timeline.js").write_text("// generated by make_voice.py: narration line spans [t0, t1] + caption words [t0, t1, word]\n"
                                   f"export const LINES = {json.dumps(lines)};\nexport const WORDS = {json.dumps(words)};\n")
    print(f"narration ends {t - GAP:.2f} s; {sum(len(json.loads((V / 'voice' / f'{l}.words.json').read_text())['words']) for l in ORDER)} words")


if __name__ == "__main__":
    main()
