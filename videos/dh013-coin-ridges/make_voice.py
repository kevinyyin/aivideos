"""dh013: tighten the ElevenLabs narration (offline, no credits) and lay it on the timeline.

voice/<id>.wav (tools/tts.py) -> pauses inside a line shortened to PAUSE, trailing silence cut, sped up by TEMPO
(ffmpeg atempo keeps the pitch) -> voice/fast/<id>.wav. Each line starts GAP after the previous one ends (BREATH at
a beat change). Writes voice/timeline.json (make_cues.py places the WAVs from it) and words.js (shots.js: line times
+ one-word caption timings).   python3 -I videos/dh013-coin-ridges/make_voice.py
"""
import json
import subprocess
import wave
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
FFMPEG = str(HERE.parents[1] / "node_modules/@ffmpeg-installer/darwin-arm64/ffmpeg")
SR = 48000
TEMPO = 1.26         # Brian at speed 1.1 reads ~2.7 words/s; good explainers run 3.4-4.1
PAUSE = 0.1           # longest pause kept inside a line (s, before TEMPO)
TAIL = 0.04
FIRST_AT = 0.12      # v2: no title card, the hook is the first sound (hits speak from frame 1-4)
GAP, BREATH = 0.06, 0.2
BREATHS = {"v03_silver", "v08_jail", "v12_ridges", "v15_today"}   # beat changes get a short breath


def read(p):
    with wave.open(str(p)) as w:
        assert w.getframerate() == SR and w.getnchannels() == 1
        return np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.float32) / 32768


def write(p, y):
    p.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(p), "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
        w.writeframes((np.clip(y, -1, 1) * 32767).astype(np.int16).tobytes())


def silences(y, thr_db=-40, min_len=0.12):
    """[(a, b)] seconds where the 10 ms RMS stays under thr_db (relative to the line's peak RMS)"""
    hop = SR // 100
    rms = np.sqrt(np.convolve(y ** 2, np.ones(hop) / hop, "same"))[::hop]
    quiet = 20 * np.log10(rms + 1e-9) < 20 * np.log10(rms.max()) + thr_db
    out, start = [], None
    for i, q in enumerate(list(quiet) + [False]):
        if q and start is None:
            start = i
        if not q and start is not None:
            if (i - start) / 100 >= min_len:
                out.append((start / 100, i / 100))
            start = None
    return out


def tighten(y):
    """cut long pauses -> (new audio, [(orig_t, new_t)] knots of the time map)"""
    dur = len(y) / SR
    cuts = []
    for a, b in silences(y):
        if b >= dur - 0.02:          # trailing silence
            cuts.append((a + TAIL, dur))
        elif a > 0.02 and b - a > PAUSE:
            cuts.append((a + PAUSE / 2, b - PAUSE / 2))
    keep, knots, t, nt = [], [(0.0, 0.0)], 0.0, 0.0
    for a, b in cuts:
        keep.append(y[int(t * SR):int(a * SR)]); nt += a - t
        knots += [(a, nt), (b, nt)]; t = b
    keep.append(y[int(t * SR):]); nt += dur - t; knots.append((dur, nt))
    return np.concatenate(keep), knots


def remap(t, knots):
    for (a0, b0), (a1, b1) in zip(knots, knots[1:]):
        if t <= a1:
            return b0 if a1 == a0 else b0 + (t - a0) * (b1 - b0) / (a1 - a0)
    return knots[-1][1]


def atempo(src, dst):
    subprocess.run([FFMPEG, "-v", "error", "-y", "-i", str(src), "-filter:a", f"atempo={TEMPO}", "-ar", str(SR), "-ac", "1", str(dst)], check=True)


def main():
    spec = json.loads((HERE / "voice.json").read_text())
    lines, words, at = [], [], None
    for ln in spec["lines"]:
        lid = ln["id"]
        y, knots = tighten(read(HERE / "voice" / f"{lid}.wav"))
        tmp = HERE / "voice" / "fast" / f"{lid}.tight.wav"
        write(tmp, y)
        out = HERE / "voice" / "fast" / f"{lid}.wav"
        atempo(tmp, out); tmp.unlink()
        dur = len(read(out)) / SR
        if at is None:
            t0 = FIRST_AT
        else:
            t0 = at + (BREATH if lid in BREATHS else GAP)
        ws = json.loads((HERE / "voice" / f"{lid}.words.json").read_text())["words"]
        lw = [[round(t0 + remap(a, knots) / TEMPO, 3), round(t0 + remap(b, knots) / TEMPO, 3), w] for w, a, b in ws]
        lines.append({"id": lid, "t": round(t0, 3), "dur": round(dur, 3), "file": f"voice/fast/{lid}.wav", "text": ln["text"], "words": lw})
        at = t0 + dur
        words += lw
    # caption: each word holds until the next word starts (no blank flicker inside a line), last word of a line +0.2 s
    cap = []
    for i, (a, b, w) in enumerate(words):
        nxt = words[i + 1][0] if i + 1 < len(words) else b + 0.3
        end = nxt if nxt - b < 0.35 else b + 0.2
        cap.append([a, round(end, 3), w.strip(".,;:!\"")])
    (HERE / "voice" / "timeline.json").write_text(json.dumps({"tempo": TEMPO, "end": round(at, 3), "lines": lines}, indent=1))
    js = "// generated by make_voice.py (do not edit): narration line times + one-word caption timings\n"
    js += "export const LINES = " + json.dumps({l["id"]: [l["t"], round(l["t"] + l["dur"], 3)] for l in lines}) + ";\n"
    js += "export const WORDS = [\n" + ",\n".join("  " + json.dumps(c) for c in cap) + ",\n];\n"
    (HERE / "words.js").write_text(js)
    n = sum(len(l["words"]) for l in lines)
    print(f"narration {FIRST_AT:.2f} -> {at:.2f} s ({at - FIRST_AT:.1f} s, {n} words, {n / (at - FIRST_AT):.2f} w/s)")
    for l in lines:
        print(f"  {l['id']:14} {l['t']:6.2f} -> {l['t'] + l['dur']:6.2f}")


if __name__ == "__main__":
    main()
